export function getPresetPrice(presetId?: string): PricingTierPrice {
  if (!presetId) return 1499;
  const match = WEDDING_PRESETS.find((p) => p.id === presetId);
  return match ? match.price : 1499;
}

export function getPresetTierName(presetId?: string): string {
  if (!presetId) return 'Classic 3D (₹1,499)';
  const match = WEDDING_PRESETS.find((p) => p.id === presetId);
  return match ? match.pricingTier : 'Classic 3D (₹1,499)';
}

export function getPlanByPrice(price: number): PricingPlan {
  const match = PRICING_PLANS.find((p) => p.price === price);
  return match || PRICING_PLANS[0];
}

